//! NIP-44 v2 encryption and epoch keys.
//!
//! All cryptography comes from the `nostr` crate. Content is always one
//! standard NIP-44 v2 payload. NIP-44 v2 encrypts 1 to [`MAX_PLAINTEXT`]
//! bytes (the `nostr` crate also allows an extended length, which other
//! implementations can't read, so it is refused here). Larger content could
//! not fit in [`crate::MAX_EVENT_BYTES`] anyway.

use nostr::nips::nip44::{self, Version};
use nostr::prelude::{Keys, PublicKey, SecretKey};

use crate::error::{ProtocolError, Result};

/// The most plaintext bytes standard NIP-44 v2 encrypts.
pub const MAX_PLAINTEXT: usize = 65_535;

/// Encrypts `plaintext` from `sender` to `recipient`.
pub fn encrypt_to(sender: &SecretKey, recipient: &PublicKey, plaintext: &str) -> Result<String> {
    if plaintext.is_empty() {
        return Err(ProtocolError::Encrypt);
    }
    if plaintext.len() > MAX_PLAINTEXT {
        return Err(ProtocolError::ContentTooLarge {
            size: plaintext.len(),
            max: MAX_PLAINTEXT,
        });
    }
    nip44::encrypt(sender, recipient, plaintext, Version::V2).map_err(|_| ProtocolError::Encrypt)
}

/// Decrypts content written by [`encrypt_to`]. NIP-44's conversation key is
/// symmetric, so either party's secret key with the other's public key works.
pub fn decrypt_from(recipient: &SecretKey, sender: &PublicKey, content: &str) -> Result<String> {
    let text = nip44::decrypt(recipient, sender, content).map_err(|_| ProtocolError::Decrypt)?;
    if text.len() > MAX_PLAINTEXT {
        return Err(ProtocolError::Decrypt);
    }
    Ok(text)
}

/// One epoch of a business's data key: a secp256k1 keypair generated by the
/// service. Acceptance content for epoch `n` is encrypted from the service
/// key to epoch `n`'s public key.
#[derive(Debug, Clone)]
pub struct EpochKey {
    pub epoch: u64,
    keys: Keys,
}

impl EpochKey {
    /// A fresh key from the operating system's random source.
    pub fn generate(epoch: u64) -> EpochKey {
        EpochKey {
            epoch,
            keys: Keys::generate(),
        }
    }

    pub fn from_secret(epoch: u64, secret: SecretKey) -> EpochKey {
        EpochKey {
            epoch,
            keys: Keys::new(secret),
        }
    }

    pub fn public_key(&self) -> PublicKey {
        self.keys.public_key()
    }

    pub fn secret_key(&self) -> &SecretKey {
        self.keys.secret_key()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn content_over_the_nip44_limit_is_refused() {
        let a = Keys::generate();
        let b = Keys::generate();
        let text = "x".repeat(MAX_PLAINTEXT + 1);
        assert_eq!(
            encrypt_to(a.secret_key(), &b.public_key(), &text),
            Err(ProtocolError::ContentTooLarge {
                size: MAX_PLAINTEXT + 1,
                max: MAX_PLAINTEXT
            })
        );
        let most = "x".repeat(MAX_PLAINTEXT);
        let sealed = encrypt_to(a.secret_key(), &b.public_key(), &most).unwrap_or_default();
        assert_eq!(
            decrypt_from(b.secret_key(), &a.public_key(), &sealed),
            Ok(most)
        );
    }

    #[test]
    fn content_round_trips_both_ways() -> Result<()> {
        let a = Keys::generate();
        let b = Keys::generate();
        let sealed = encrypt_to(a.secret_key(), &b.public_key(), "hello")?;
        // Symmetric: the sender can read it back with the recipient's public key.
        assert_eq!(
            decrypt_from(a.secret_key(), &b.public_key(), &sealed)?,
            "hello"
        );
        Ok(())
    }

    #[test]
    fn a_third_key_cannot_decrypt() -> Result<()> {
        let a = Keys::generate();
        let b = Keys::generate();
        let c = Keys::generate();
        let sealed = encrypt_to(a.secret_key(), &b.public_key(), "hello")?;
        assert_eq!(
            decrypt_from(c.secret_key(), &a.public_key(), &sealed),
            Err(ProtocolError::Decrypt)
        );
        Ok(())
    }
}
