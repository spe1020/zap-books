//! NIP-44 v2 encryption, with chunking for long content, and epoch keys.
//!
//! All cryptography comes from the `nostr` crate. NIP-44 v2 encrypts 1 to
//! 65,535 bytes; longer content (a large import) is split at character
//! boundaries into chunks of at most [`MAX_CHUNK`] bytes, each encrypted on
//! its own, and sent as a JSON array of NIP-44 payloads. A base64 payload
//! never starts with `[`, so the two forms can't be confused.

use nostr::nips::nip44::{self, Version};
use nostr::prelude::{Keys, PublicKey, SecretKey};

use crate::error::{ProtocolError, Result};

/// The most plaintext bytes NIP-44 v2 encrypts in one payload.
pub const MAX_CHUNK: usize = 65_535;

/// Encrypts `plaintext` from `sender` to `recipient`.
pub fn encrypt_to(sender: &SecretKey, recipient: &PublicKey, plaintext: &str) -> Result<String> {
    if plaintext.is_empty() {
        return Err(ProtocolError::Encrypt);
    }
    let encrypt = |chunk: &str| {
        nip44::encrypt(sender, recipient, chunk, Version::V2).map_err(|_| ProtocolError::Encrypt)
    };
    if plaintext.len() <= MAX_CHUNK {
        return encrypt(plaintext);
    }
    let payloads = chunks(plaintext)
        .into_iter()
        .map(encrypt)
        .collect::<Result<Vec<_>>>()?;
    serde_json::to_string(&payloads).map_err(|_| ProtocolError::Encrypt)
}

/// Decrypts content written by [`encrypt_to`]. NIP-44's conversation key is
/// symmetric, so either party's secret key with the other's public key works.
pub fn decrypt_from(recipient: &SecretKey, sender: &PublicKey, content: &str) -> Result<String> {
    let decrypt = |payload: &str| {
        nip44::decrypt(recipient, sender, payload).map_err(|_| ProtocolError::Decrypt)
    };
    if !content.starts_with('[') {
        return decrypt(content);
    }
    let payloads: Vec<String> =
        serde_json::from_str(content).map_err(|_| ProtocolError::Decrypt)?;
    // A one-element array is never written, so accepting it would give one
    // plaintext two encodings.
    if payloads.len() < 2 {
        return Err(ProtocolError::Decrypt);
    }
    payloads.iter().map(|p| decrypt(p)).collect()
}

/// Splits `s` into pieces of at most [`MAX_CHUNK`] bytes, never inside a
/// character.
fn chunks(s: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut rest = s;
    while rest.len() > MAX_CHUNK {
        let mut cut = MAX_CHUNK;
        while !rest.is_char_boundary(cut) {
            cut -= 1;
        }
        let (head, tail) = rest.split_at(cut);
        out.push(head);
        rest = tail;
    }
    if !rest.is_empty() {
        out.push(rest);
    }
    out
}

/// One epoch of a business's data key: a secp256k1 keypair generated by the
/// service. Acceptance content for epoch `n` is encrypted from the service
/// key to epoch `n`'s public key.
#[derive(Debug, Clone)]
pub struct EpochKey {
    pub epoch: u64,
    keys: Keys,
}

impl EpochKey {
    /// A fresh key from the operating system's random source.
    pub fn generate(epoch: u64) -> EpochKey {
        EpochKey {
            epoch,
            keys: Keys::generate(),
        }
    }

    pub fn from_secret(epoch: u64, secret: SecretKey) -> EpochKey {
        EpochKey {
            epoch,
            keys: Keys::new(secret),
        }
    }

    pub fn public_key(&self) -> PublicKey {
        self.keys.public_key()
    }

    pub fn secret_key(&self) -> &SecretKey {
        self.keys.secret_key()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn chunks_never_split_a_character() {
        // 'é' is two bytes, so MAX_CHUNK falls inside one.
        let s = format!("a{}", "é".repeat(MAX_CHUNK));
        let parts = chunks(&s);
        assert!(parts.len() > 2);
        assert!(parts.iter().all(|p| p.len() <= MAX_CHUNK));
        assert_eq!(parts.concat(), s);
    }

    #[test]
    fn long_content_round_trips_in_chunks() -> Result<()> {
        let a = Keys::generate();
        let b = Keys::generate();
        let text = "x".repeat(MAX_CHUNK * 2 + 10);
        let sealed = encrypt_to(a.secret_key(), &b.public_key(), &text)?;
        assert!(sealed.starts_with('['));
        assert_eq!(
            decrypt_from(b.secret_key(), &a.public_key(), &sealed)?,
            text
        );
        Ok(())
    }

    #[test]
    fn short_content_is_one_payload() -> Result<()> {
        let a = Keys::generate();
        let b = Keys::generate();
        let sealed = encrypt_to(a.secret_key(), &b.public_key(), "hello")?;
        assert!(!sealed.starts_with('['));
        // Symmetric: the sender can read it back with the recipient's public key.
        assert_eq!(
            decrypt_from(a.secret_key(), &b.public_key(), &sealed)?,
            "hello"
        );
        Ok(())
    }

    #[test]
    fn a_third_key_cannot_decrypt() -> Result<()> {
        let a = Keys::generate();
        let b = Keys::generate();
        let c = Keys::generate();
        let sealed = encrypt_to(a.secret_key(), &b.public_key(), "hello")?;
        assert_eq!(
            decrypt_from(c.secret_key(), &a.public_key(), &sealed),
            Err(ProtocolError::Decrypt)
        );
        Ok(())
    }

    #[test]
    fn a_single_chunk_array_is_refused() -> Result<()> {
        let a = Keys::generate();
        let b = Keys::generate();
        let one = encrypt_to(a.secret_key(), &b.public_key(), "hello")?;
        let wrapped = serde_json::to_string(&[one]).map_err(|_| ProtocolError::Encrypt)?;
        assert_eq!(
            decrypt_from(b.secret_key(), &a.public_key(), &wrapped),
            Err(ProtocolError::Decrypt)
        );
        Ok(())
    }
}
